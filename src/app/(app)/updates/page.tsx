import Link from "next/link";
import { getCurrentTenantIfEntitled, hasRole } from "@/lib/tenant";
import { getSkillModule, isSupportedSkillName } from "@/services/skill-runner/skills";
import { LEGAL_UPDATE_CHECK_CRON, LEGAL_UPDATE_CHECK_TZ } from "@/services/queue/monitoring-jobs";
import { SOURCE_GROUP_LABELS, SOURCES, type SourceGroup } from "@/services/monitoring/sources";
import {
  countUnreviewedLegalUpdates,
  getLegalUpdateMonitorStatus,
  LEGAL_UPDATE_CHECK_ROLES,
  LEGAL_UPDATE_REVIEW_ROLES,
  listLegalUpdatesForTenant,
  REVIEW_NOTE_MAX_CHARS,
  UNREVIEWED_WINDOW_DAYS,
  type LegalUpdateListItem,
  type LegalUpdateView,
  type MonitorStatus,
} from "@/services/monitoring/service";
import { CheckNowButton } from "./CheckNowButton";
import { ReviewControl } from "./ReviewControl";

const VIEWS: [LegalUpdateView, string][] = [
  ["unreviewed", "Unreviewed"],
  ["all", "All"],
  ["screened", "Screened out"],
];

const GROUPS = Object.keys(SOURCE_GROUP_LABELS) as SourceGroup[];

function first(value: string | string[] | undefined): string | undefined {
  return Array.isArray(value) ? value[0] : value;
}

function formatUtc(date: Date | null | undefined): string {
  if (!date) return "never";
  return `${date.toLocaleString("en-US", { timeZone: "UTC", dateStyle: "medium", timeStyle: "short" })} UTC`;
}

function formatDay(date: Date): string {
  return date.toLocaleDateString("en-US", { timeZone: "UTC", dateStyle: "medium" });
}

function skillLabel(name: string): string {
  return isSupportedSkillName(name) ? getSkillModule(name).label : name;
}

function safeHref(url: string): string | null {
  return url.startsWith("https://") ? url : null;
}

function hrefWith(params: { view: LegalUpdateView; group?: string | null; skill?: string | null }): string {
  const search = new URLSearchParams();
  search.set("view", params.view);
  if (params.group) search.set("source", params.group);
  if (params.skill) search.set("skill", params.skill);
  return `/updates?${search.toString()}`;
}

const badge = "rounded px-1.5 py-0.5 text-xs font-medium";
const muted = "text-black/60 dark:text-white/60";

export default async function LegalUpdatesPage({
  searchParams,
}: {
  searchParams: Promise<{ [key: string]: string | string[] | undefined }>;
}) {
  const current = await getCurrentTenantIfEntitled();
  if (!current) return null;
  const { tenant, membership, userId } = current;
  const params = await searchParams;
  const viewParam = first(params.view);
  const view: LegalUpdateView = viewParam === "all" || viewParam === "screened" ? viewParam : "unreviewed";
  const groupParam = first(params.source);
  const group = GROUPS.includes(groupParam as SourceGroup) ? (groupParam as SourceGroup) : null;
  const skillParam = first(params.skill);
  const skill = skillParam && isSupportedSkillName(skillParam) ? skillParam : null;

  const [items, unreviewed, status] = await Promise.all([
    listLegalUpdatesForTenant(tenant.id, { view, group, skill }),
    countUnreviewedLegalUpdates(tenant.id),
    getLegalUpdateMonitorStatus(tenant.id),
  ]);
  // The actions check the role too; this only hides controls the role cannot use.
  const canReview = hasRole(membership, LEGAL_UPDATE_REVIEW_ROLES);
  const canCheck = hasRole(membership, LEGAL_UPDATE_CHECK_ROLES);

  return (
    <div className="mx-auto flex w-full max-w-4xl flex-col gap-6">
      <div className="flex flex-col gap-2">
        <h1 className="text-xl font-semibold">Legal updates</h1>
        <p className={`text-sm ${muted}`}>
          New AG and BIA precedent decisions, EOIR policy memoranda and practice manual changes, EOIR notices,
          Federal Register documents, USCIS form editions and Policy Manual updates, and published court of
          appeals immigration opinions, checked every day early in the morning (U.S. Central time) at the official
          sources, together with what the app&apos;s <Link href="/library" className="underline">library</Link> collected
          that day from the sources it follows. Each item shows the official text as the source lists it, with its link. The summary under it was generated by the app
          strictly from that quoted text and is flagged for attorney verification: read the official source
          before relying on any item. Skill runs see published items matched to them, with the same flag.
        </p>
      </div>

      <StatusPanel status={status} canCheck={canCheck} />

      <div className="flex flex-col gap-2 text-sm">
        <div className="flex flex-wrap items-center gap-3">
          {VIEWS.map(([key, label]) => (
            <Link
              key={key}
              href={hrefWith({ view: key, group, skill })}
              className={key === view ? "font-semibold underline" : `${muted} hover:underline`}
            >
              {label}
              {key === "unreviewed" ? ` (${unreviewed})` : ""}
            </Link>
          ))}
        </div>
        <div className="flex flex-wrap items-center gap-3">
          <span className={muted}>Source:</span>
          <Link href={hrefWith({ view, skill })} className={!group ? "font-semibold underline" : `${muted} hover:underline`}>
            All
          </Link>
          {GROUPS.map((g) => (
            <Link
              key={g}
              href={hrefWith({ view, group: g, skill })}
              className={g === group ? "font-semibold underline" : `${muted} hover:underline`}
            >
              {SOURCE_GROUP_LABELS[g]}
            </Link>
          ))}
          {skill && (
            <span className={muted}>
              Skill: {skillLabel(skill)} (<Link href={hrefWith({ view, group })} className="underline">clear</Link>)
            </span>
          )}
        </div>
        {view === "unreviewed" && (
          <p className={`text-xs ${muted}`}>
            Unreviewed lists items from the last {UNREVIEWED_WINDOW_DAYS} days that no one at the firm has marked reviewed.
          </p>
        )}
        {view === "screened" && (
          <p className={`text-xs ${muted}`}>
            Items read and left out under the skill&apos;s source rules (for example another circuit&apos;s opinion on a
            topic routing.md does not keep, or a notice outside the kept subjects), with the reason for each.
          </p>
        )}
      </div>

      {items.length === 0 ? (
        <p className={`rounded-lg border border-black/10 p-6 text-center text-sm dark:border-white/10 ${muted}`}>
          {status.lastRun
            ? view === "unreviewed"
              ? "Nothing to review. New items appear here after each day's check."
              : "No items match this view."
            : "No check has run yet. The first check of each source records what is already published as the baseline, so only later publications appear here."}
        </p>
      ) : (
        <div className="flex flex-col gap-4">
          {items.map((item) => (
            <UpdateCard key={item.id} item={item} canReview={canReview} userId={userId} view={view} group={group} />
          ))}
          {items.length >= 100 && <p className={`text-xs ${muted}`}>Showing the newest 100 items. Narrow the view to see older ones.</p>}
        </div>
      )}
    </div>
  );
}

function StatusPanel({ status, canCheck }: { status: MonitorStatus; canCheck: boolean }) {
  const run = status.lastRun;
  const checksBySource = new Map(status.sources.map((c) => [c.source, c]));
  const totals = (run?.totals ?? null) as Record<string, number> | null;
  return (
    <section className="flex flex-col gap-3 rounded-lg border border-black/10 p-4 text-sm dark:border-white/10">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="flex flex-col gap-1">
          <span className="font-semibold">Source checks</span>
          <span className={muted}>
            Scheduled every day at 05:00 U.S. Central time (cron &quot;{LEGAL_UPDATE_CHECK_CRON}&quot;, {LEGAL_UPDATE_CHECK_TZ}). Last check:{" "}
            {run ? `${formatUtc(run.startedAt)}, ${run.trigger === "manual" ? "started by hand" : "scheduled"}, ${run.status}` : "none yet"}.
          </span>
          {run && totals && (
            <span className={muted}>
              {totals.sourcesChecked ?? 0} sources checked, {totals.sourcesFailed ?? 0} failed; {totals.newItems ?? 0} new
              and {totals.revisedItems ?? 0} revised items; {totals.summarized ?? 0} summarized, {totals.screened ?? 0} screened
              out, {totals.leftPending ?? 0} waiting for a summary.
            </span>
          )}
          {run?.errorMessage && <span className="text-red-700 dark:text-red-300">{run.errorMessage}</span>}
        </div>
        {canCheck && <CheckNowButton />}
      </div>
      <details>
        <summary className="cursor-pointer text-xs font-medium">Each source&apos;s latest check</summary>
        <table className="mt-2 w-full text-xs">
          <thead>
            <tr className="border-b border-black/10 text-left dark:border-white/10">
              <th className="py-1 pr-2">Source</th>
              <th className="pr-2">Checked</th>
              <th className="pr-2">Result</th>
              <th className="pr-2">Listed</th>
              <th className="pr-2">New</th>
              <th>Notes</th>
            </tr>
          </thead>
          <tbody>
            {SOURCES.map((source) => {
              const check = checksBySource.get(source.key);
              const notes = [...((check?.notes as string[] | null) ?? []), ...(check?.errorMessage ? [check.errorMessage] : [])];
              const tone =
                check?.status === "failed"
                  ? "text-red-700 dark:text-red-300"
                  : check?.status === "not_checked"
                    ? "text-amber-700 dark:text-amber-300"
                    : "";
              return (
                <tr key={source.key} className="border-b border-black/5 align-top dark:border-white/5">
                  <td className="py-1 pr-2">
                    {safeHref(source.homeUrl) ? (
                      <a href={source.homeUrl} target="_blank" rel="noopener noreferrer" className="underline">
                        {source.label}
                      </a>
                    ) : (
                      source.label
                    )}
                  </td>
                  <td className="pr-2">{check ? formatUtc(check.startedAt) : "never"}</td>
                  <td className={`pr-2 ${tone}`}>{check ? check.status.replace(/_/g, " ") : "not yet"}</td>
                  <td className="pr-2">{check?.itemsSeen ?? ""}</td>
                  <td className="pr-2">{check ? check.newItems + check.revisedItems : ""}</td>
                  <td className={muted}>{notes.join(" ")}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </details>
    </section>
  );
}

function UpdateCard({
  item,
  canReview,
  userId,
  view,
  group,
}: {
  item: LegalUpdateListItem;
  canReview: boolean;
  userId: string;
  view: LegalUpdateView;
  group: SourceGroup | null;
}) {
  const official = safeHref(item.officialUrl);
  const listedOn = safeHref(item.listedOnUrl);
  const analysis = item.analysis;
  const bases = analysis?.affectedSkillBases ?? [];
  const firmTextChecks = analysis?.checkAgainstFirmText ?? [];
  const needsDecision = analysis?.needsDecision ?? [];
  const facts = Object.entries(item.listingFacts).filter(
    ([key]) => !["volumePage", "federalRegisterPage", "librarySource", "libraryDocumentId"].includes(key)
  );
  const libraryDocumentId = /^[0-9a-f-]{36}$/i.test(item.listingFacts.libraryDocumentId ?? "") ? item.listingFacts.libraryDocumentId : null;

  return (
    <article className="flex flex-col gap-3 rounded-lg border border-black/10 p-4 dark:border-white/10">
      <div className="flex flex-wrap items-center gap-2">
        <span className={`${badge} bg-black/5 dark:bg-white/10`}>{item.itemType}</span>
        <span className={`${badge} bg-amber-100 text-amber-900 dark:bg-amber-950 dark:text-amber-200`}>
          Flagged for attorney verification
        </span>
        {item.isRevision && <span className={`${badge} bg-blue-100 text-blue-900 dark:bg-blue-950 dark:text-blue-200`}>Changed listing</span>}
        {item.status === "pending_summary" && <span className={`${badge} bg-black/5 dark:bg-white/10`}>Summary pending</span>}
        {item.status === "summary_failed" && (
          <span className={`${badge} bg-red-100 text-red-900 dark:bg-red-950 dark:text-red-200`}>No summary</span>
        )}
        {item.status === "screened" && <span className={`${badge} bg-black/5 dark:bg-white/10`}>Screened out</span>}
        <span className={`text-xs ${muted}`}>{item.sourceLabel}</span>
      </div>

      <div className="flex flex-col gap-1">
        <h2 className="font-semibold">
          {item.title}
          {item.citation && <span className="font-normal">, {item.citation}</span>}
        </h2>
        <p className={`text-xs ${muted}`}>
          Published: {item.publishedDateText ? `${item.publishedDateText} (as the source states it)` : "no date stated on the listing"}.
          Retrieved {formatDay(item.retrievedAt)}.
        </p>
        {item.courtWeight && <p className="text-xs font-medium">Weight: {item.courtWeight}</p>}
      </div>

      <div className="flex flex-col gap-1 text-sm">
        <span className="text-xs font-medium uppercase tracking-wide text-black/50 dark:text-white/50">
          Summary (generated from the quoted text; unverified)
        </span>
        {item.aiSummary ? <p>{item.aiSummary}</p> : <p className={muted}>{item.statusReason ?? "Not summarized yet."}</p>}
        {item.status === "screened" && item.statusReason && <p className={`text-xs ${muted}`}>{item.statusReason}</p>}
      </div>

      <div className="flex flex-col gap-1">
        <span className="text-xs font-medium uppercase tracking-wide text-black/50 dark:text-white/50">
          Official text, as the source lists it
        </span>
        <blockquote className="whitespace-pre-line border-l-2 border-black/20 pl-3 text-sm dark:border-white/20">
          {item.rawExcerpt}
        </blockquote>
        {facts.length > 0 && (
          <p className={`text-xs ${muted}`}>{facts.map(([key, value]) => `${key.replace(/([A-Z])/g, " $1").toLowerCase()}: ${value}`).join("; ")}</p>
        )}
      </div>

      {item.documentQuotes.length > 0 && (
        <details className="text-sm">
          <summary className="cursor-pointer text-xs font-medium">
            Quoted from the document ({item.documentQuotes.length} passage{item.documentQuotes.length === 1 ? "" : "s"}, cited by page)
          </summary>
          <ul className="mt-2 flex flex-col gap-2">
            {item.documentQuotes.map((q, i) => (
              <li key={i} className="border-l-2 border-black/20 pl-3 dark:border-white/20">
                <span className={`text-xs ${muted}`}>
                  {q.label || "Passage"}
                  {q.startPage !== null ? `, ${q.endPage !== null && q.endPage !== q.startPage ? `pp. ${q.startPage}-${q.endPage}` : `p. ${q.startPage}`}` : ""}
                </span>
                <p>&quot;{q.text}&quot;</p>
              </li>
            ))}
          </ul>
        </details>
      )}

      <p className="break-all text-xs">
        Official source:{" "}
        {official ? (
          <a href={official} target="_blank" rel="noopener noreferrer" className="underline">
            {item.officialUrl}
          </a>
        ) : (
          item.officialUrl
        )}
        {listedOn && listedOn !== official && (
          <>
            {" "}
            (listed on{" "}
            <a href={listedOn} target="_blank" rel="noopener noreferrer" className="underline">
              {item.listedOnUrl}
            </a>
            )
          </>
        )}
        {libraryDocumentId && (
          <>
            {" "}
            (<Link href={`/library/documents/${libraryDocumentId}`} className="underline">
              the library&apos;s copy
            </Link>
            )
          </>
        )}
      </p>

      {item.affectedSkills.length > 0 && (
        <div className="flex flex-col gap-1 text-xs">
          <span className="font-medium">Skills this may affect</span>
          <div className="flex flex-wrap gap-1.5">
            {item.affectedSkills.map((name) => (
              <Link
                key={name}
                href={hrefWith({ view, group, skill: name })}
                title={bases.filter((b) => b.skill === name).map((b) => b.basis).join("\n")}
                className={`${badge} bg-black/5 hover:underline dark:bg-white/10`}
              >
                {skillLabel(name)}
              </Link>
            ))}
          </div>
        </div>
      )}

      {firmTextChecks.length > 0 && (
        <div className="rounded-md border border-amber-300 bg-amber-50 p-3 text-xs text-amber-900 dark:border-amber-900 dark:bg-amber-950 dark:text-amber-100">
          <span className="font-medium">Check the firm&apos;s reference text</span>
          <ul className="mt-1 list-disc pl-4">
            {firmTextChecks.map((c, i) => (
              <li key={i}>
                {c.file}, {c.heading.replace(/^#+\s*/, "")}: {c.note}
              </li>
            ))}
          </ul>
        </div>
      )}

      {needsDecision.length > 0 && (
        <div className="text-xs">
          <span className="font-medium">Needs a decision</span>
          <ul className={`mt-1 list-disc pl-4 ${muted}`}>
            {needsDecision.map((n, i) => (
              <li key={i}>{n}</li>
            ))}
          </ul>
        </div>
      )}

      <ReviewControl
        legalUpdateId={item.id}
        review={item.review ? { reviewedAt: formatDay(item.review.reviewedAt), note: item.review.note } : null}
        reviewedByYou={item.review?.reviewedBy === userId}
        canReview={canReview}
        noteMaxChars={REVIEW_NOTE_MAX_CHARS}
      />
    </article>
  );
}

